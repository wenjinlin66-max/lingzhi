def generate_icebreakers(vibe_key: str) -> list[str]:
    prompts = {
        "anxious": [
            "今天让你最疲惫的瞬间是什么？",
            "如果现在有人真的懂你，你最想先说哪一句？",
            "你觉得自己现在最需要的是建议、陪伴，还是安静？",
        ],
        "lonely": [
            "最近一次你特别想被理解，是因为什么？",
            "今晚的你更想被倾听，还是更想说出来？",
            "有没有一句你一直没找到机会说出口的话？",
        ],
        "happy": [
            "今天有什么小事让你突然心情变好了？",
            "如果把这份好心情分享给陌生人，你会怎么说？",
            "你现在最想把哪种能量传给别人？",
        ],
    }
    return prompts.get(
        vibe_key,
        [
            "你最近最想被理解的一件事是什么？",
            "今天最想说出来的一句话是什么？",
            "如果有人愿意认真听你说三分钟，你会先从哪里开始？",
        ],
    )
